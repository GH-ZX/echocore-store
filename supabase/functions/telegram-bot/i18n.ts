export type StringKey = keyof typeof STRINGS.en;

export function tr(lang: Lang, key: StringKey, vars: Record<string, string | number> = {}): string {
  let text: string = (STRINGS[lang] as Record<string, string>)[key] ?? STRINGS.en[key];
  for (const [k, v] of Object.entries(vars)) text = text.split(`{${k}}`).join(String(v));
  return text;
}

export function langFromTelegram(code?: string | null): Lang {
  const c = String(code || '').toLowerCase();
  return !c || c.startsWith('ar') ? 'ar' : 'en';
}
